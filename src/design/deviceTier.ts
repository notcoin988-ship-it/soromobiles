import * as Device from 'expo-device';

/**
 * Класс устройства по объёму памяти (§12).
 *
 * «На устройствах с < 3 ГБ ОЗУ [свечение] заменяется статичным PNG».
 * Мы идём чуть дальше и просто не рисуем слой: три полупрозрачных
 * радиальных градиента поверх всего экрана — это лишний проход композитора
 * на каждом кадре, а именно на таких устройствах бюджет кадра и так выбран
 * прокруткой ленты.
 *
 * Порог из ТЗ. Целевые аппараты из матрицы §12 — Redmi 9A с 2 ГБ и Galaxy A12
 * с 3 ГБ, то есть граница проходит ровно между ними.
 *
 * Значение читается ОДИН раз при старте: объём памяти в течение сессии не
 * меняется, а обращение к нативному модулю на каждый рендер стоит дороже
 * самого эффекта.
 */

const BYTES_IN_GB = 1024 * 1024 * 1024;
export const LOW_MEMORY_THRESHOLD_GB = 3;

/**
 * true, если устройство слабое. При неизвестном объёме памяти считаем
 * устройство НОРМАЛЬНЫМ: эмуляторы и часть прошивок не отдают totalMemory,
 * и глушить оформление у всех из-за этого неправильно.
 */
export const isLowMemoryDevice: boolean =
  typeof Device.totalMemory === 'number' &&
  Device.totalMemory > 0 &&
  Device.totalMemory < LOW_MEMORY_THRESHOLD_GB * BYTES_IN_GB;

/** Объём памяти в гигабайтах — для экрана диагностики и отчётов. */
export const totalMemoryGb: number | null =
  typeof Device.totalMemory === 'number' && Device.totalMemory > 0
    ? Math.round((Device.totalMemory / BYTES_IN_GB) * 10) / 10
    : null;
