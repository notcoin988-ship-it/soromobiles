/**
 * Согласие с документами и его версия (§8.1).
 *
 * ТЗ: «Экран дисклеймера показывается один раз; факт согласия и версия
 * документов сохраняются локально. При смене версии документов — показывается
 * повторно».
 *
 * ВЕРСИЯ — ЭТО ДАТА РЕДАКЦИИ, вшитой в приложение. Не выдуманный счётчик и не
 * поле с сервера: документы лежат прямо в бандле (privacyPolicy.ts), и когда
 * юристы дадут новую редакцию, вместе с текстом поменяется его дата — а значит
 * и эта строка. Забыть поднять версию, обновив текст, невозможно: дата стоит
 * в самом документе, и тест сверяет их между собой.
 *
 * Когда появится `/v1/config` (B6), сюда можно будет добавить серверное
 * значение с приоритетом — например, чтобы заставить пересогласиться раньше
 * выпуска приложения. Пока источник один и он локальный.
 */

/** Дата редакции обоих документов — она же версия согласия. */
export const LEGAL_DOCS_VERSION = '2026-01-15';

/**
 * Нужно ли показать дисклеймер.
 *
 * Не совпало — показываем: и когда согласия не было вовсе (null), и когда оно
 * дано на прошлую редакцию. Разбирать эти случаи по-разному незачем — в обоих
 * человек ещё не соглашался с тем, что действует сейчас.
 */
export function needsConsent(
  acceptedVersion: string | null,
  currentVersion: string = LEGAL_DOCS_VERSION,
): boolean {
  return acceptedVersion !== currentVersion;
}
