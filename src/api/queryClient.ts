import { QueryClient } from '@tanstack/react-query';

import { CONFIG_TTL_MS } from '../store/configTtl';

/**
 * Клиент TanStack Query (§4.2: «Состояние сервера: TanStack Query — кэш,
 * ретраи, инвалидация»).
 *
 * Два решения, которые здесь важнее остальных.
 *
 * 1. РЕТРАИ ВЫКЛЮЧЕНЫ. Это не упрощение, а исправление двойной работы:
 *    ApiClient уже повторяет запросы по §5.3 — три попытки 1 → 3 → 7 секунд
 *    с джиттером, и только для идемпотентных. Оставь ретраи ещё и здесь,
 *    получилось бы до девяти попыток и до полутора минут ожидания на
 *    запрос, который сервер отверг по существу.
 *
 * 2. ОШИБКИ НЕ БРОСАЮТСЯ. ApiClient возвращает типизированный ApiError, а не
 *    исключение (§5.3), поэтому в queryFn мы сами превращаем неуспех в
 *    throw — иначе Query считает ошибку успешным ответом и кэширует её.
 */
export const queryClient = new QueryClient({
  defaultOptions: {
    queries: {
      retry: false,
      /**
       * Сеть в школах Таджикистана нестабильна, поэтому данные считаются
       * свежими минуту: возврат на экран не должен дёргать сервер заново.
       * Для конфига срок переопределяется на 24 часа (§6.6).
       */
      staleTime: 60_000,
      gcTime: CONFIG_TTL_MS,
      /**
       * Перезапрос при возврате в приложение — да, при каждом монтировании —
       * нет. Список чатов мог измениться на другом устройстве, но открытие
       * drawer не повод идти в сеть: он читается из SQLite (§10).
       */
      refetchOnMount: false,
      refetchOnReconnect: true,
      refetchOnWindowFocus: false,
    },
    mutations: {
      retry: false,
    },
  },
});

/**
 * Ключи кэша в одном месте. Разъехавшийся ключ — самая частая причина того,
 * что инвалидация «не работает»: список обновляют по одному ключу, а читают
 * по другому, и ошибка не видна ни типам, ни линтеру.
 */
export const queryKeys = {
  chats: ['chats'] as const,
  chat: (id: string) => ['chat', id] as const,
  config: ['config'] as const,
  usage: ['usage'] as const,
};
