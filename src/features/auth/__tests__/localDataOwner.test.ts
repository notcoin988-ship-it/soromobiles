import { describe, it } from 'node:test';

import { expect } from '../../../test/expect';
import { shouldWipeLocalData } from '../localDataOwner';

/**
 * Владелец локальной базы (§11).
 *
 * Правило выглядит тривиально, но у него три разных случая, и ошибка в любом
 * из них — это либо утечка переписки чужому человеку, либо стёртая история у
 * своего. Поэтому оно вынесено из стора и зафиксировано тестом.
 */
describe('владелец локальных данных', () => {
  it('свой аккаунт вернулся — база остаётся на месте', () => {
    // Иначе выход и вход обратно стирали бы офлайн-историю каждый раз, а §10
    // обещает, что переписка открывается в самолёте.
    expect(shouldWipeLocalData('user-1', 'user-1')).toBe(false);
  });

  it('вошёл другой — база стирается', () => {
    // Тот самый случай, что воспроизвели вживую: второй аккаунт видел в
    // drawer чат первого.
    expect(shouldWipeLocalData('user-1', 'user-2')).toBe(true);
  });

  it('владелец неизвестен — тоже стираем', () => {
    // Чистая установка: база пуста, вызов ничего не стоит. Обновление со
    // старой версии: на диске может лежать чужое, и один раз потерять
    // офлайн-историю лучше, чем показать её не тому.
    expect(shouldWipeLocalData(null, 'user-1')).toBe(true);
  });
});
