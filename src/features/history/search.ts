/**
 * Поиск по локальной истории (§8.4: «фильтрует локальную БД по заголовку и по
 * тексту сообщений»).
 *
 * Две вещи, которые ломают поиск незаметно, и потому вынесены сюда под тесты.
 *
 * 1. Спецсимволы LIKE. Если подставить запрос в шаблон как есть, введённый
 *    человеком знак `%` совпадёт со всем подряд, а `_` — с любым символом.
 *    Пользователь при этом видит не «ничего не найдено», а случайный список.
 *
 * 2. Регистр. LIKE в SQLite приводит регистр только для ASCII: 'Салом' и
 *    'салом' для него РАЗНЫЕ строки, потому что кириллица вне ASCII. Поэтому
 *    и запрос, и содержимое колонок приводятся к нижнему регистру в JS —
 *    отсюда колонки title_lower и content_lower в схеме.
 */

/** Символ экранирования для `LIKE ? ESCAPE '\'`. */
export const LIKE_ESCAPE = '\\';

export function escapeLike(input: string): string {
  // Обратный слэш экранируется первым, иначе экранирующие слэши, добавленные
  // для % и _, будут экранированы повторно.
  return input.replace(/\\/g, '\\\\').replace(/[%_]/g, (c) => `\\${c}`);
}

/**
 * Приведение к нижнему регистру с учётом языка. Для таджикской кириллицы
 * важно именно toLocaleLowerCase: у турецкой I правила другие, и явная локаль
 * защищает от неожиданностей на устройстве с турецкими настройками.
 */
export function normalizeForSearch(input: string): string {
  return input.toLocaleLowerCase('ru');
}

/**
 * Шаблон для LIKE или null, если искать нечего. Пустой запрос — это «показать
 * всё», а не «найти пустую строку»: иначе список схлопнется при первом же
 * стирании текста.
 */
export function likePattern(query: string): string | null {
  const trimmed = query.trim();
  if (trimmed.length === 0) return null;
  return `%${escapeLike(normalizeForSearch(trimmed))}%`;
}
