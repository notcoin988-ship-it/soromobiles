/**
 * Правило «онлайн или нет» (§8.7).
 *
 * Вынесено из network.ts отдельным файлом намеренно: тот импортирует нативный
 * модуль NetInfo и в обычном Node не поднимается, а это правило обязано быть
 * под тестами. Здесь нет ни одного импорта — только логика.
 *
 * От неё зависят три различимых состояния ошибки: только она отличает «нет
 * интернета» от «сервер недоступен». Для учителя в Хороге это разные вещи —
 * в первом случае подождать, во втором жаловаться (§10).
 */

/** Структурный минимум от NetInfoState — только то, что влияет на решение. */
export type ConnectivitySnapshot = {
  isConnected: boolean | null;
  isInternetReachable: boolean | null;
};

export function resolveConnectivity(state: ConnectivitySnapshot): boolean {
  // Интерфейса нет — вопрос закрыт.
  if (state.isConnected === false) return false;

  // Интерфейс есть, но через него ничего не ходит: школьный Wi-Fi без
  // интернета — обычное дело. По одному isConnected он выглядит рабочим, и
  // пользователь получил бы «сервер недоступен» вместо честного «интернета
  // нет, сообщение в очереди».
  if (state.isInternetReachable === false) return false;

  // null означает «проверка ещё идёт». Объявлять офлайн в этот момент нельзя:
  // на холодном старте это дало бы ложное «интернета нет» на первом запросе.
  return true;
}
