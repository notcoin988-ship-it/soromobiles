import { describe, it } from 'node:test';

import { expect } from '../../../test/expect';
import { escapeLike, likePattern, normalizeForSearch } from '../search';

describe('поиск по истории (§8.4)', () => {
  it('пустой запрос — это «показать всё», а не «найти пустую строку»', () => {
    expect(likePattern('')).toBe(null);
    expect(likePattern('   ')).toBe(null);
  });

  it('обрамляет запрос процентами — поиск по вхождению, а не по началу', () => {
    expect(likePattern('салом')).toBe('%салом%');
  });

  it('приводит запрос к нижнему регистру: LIKE в SQLite кириллицу не приводит', () => {
    // Заголовок чата — первые 30 символов вопроса, он почти всегда с большой
    // буквы. Без этого поиск «салом» не нашёл бы чат «Салом, чӣ хел?».
    expect(likePattern('Салом')).toBe('%салом%');
    expect(normalizeForSearch('ҲАМА')).toBe('ҳама');
  });

  it('экранирует % — иначе один знак покажет весь список', () => {
    expect(likePattern('100%')).toBe('%100\\%%');
  });

  it('экранирует _ — иначе он совпадёт с любым символом', () => {
    expect(likePattern('a_b')).toBe('%a\\_b%');
  });

  it('обратный слэш экранируется первым, без двойной обработки', () => {
    // Сначала \ → \\, и только потом % → \%. Обратный порядок дал бы \\% и
    // сломал бы шаблон.
    expect(escapeLike('\\%')).toBe('\\\\\\%');
  });

  it('обычный текст не портится', () => {
    expect(escapeLike('масъалаи математика')).toBe('масъалаи математика');
  });
});
