import * as WebBrowser from 'expo-web-browser';

import { themes, type ThemeName } from '../../design/tokens';

/**
 * Открыть юридический документ, которого нет в приложении.
 *
 * §8.1, дословно: ссылки на документы «открываются во встроенном браузере
 * (expo-web-browser / SafariViewController / Custom Tabs), а не выкидывают из
 * приложения». Linking.openURL запускает Chrome отдельным приложением: человек
 * теряет заполненную форму регистрации и возвращается кнопкой «назад» через
 * системный переключатель задач — если догадается вернуться вообще.
 *
 * Встроенный браузер открывается ПОВЕРХ приложения, закрывается крестиком и
 * оставляет экран под собой нетронутым.
 *
 * Политика конфиденциальности сюда не попадает: её текст вшит в приложение и
 * показывается своим окном, которое работает и без сети (см. privacyPolicy.ts).
 * Здесь — только то, чего у нас нет: условия использования и поддержка.
 */
export async function openDocument(url: string, themeName: ThemeName): Promise<void> {
  if (!url) return;

  const theme = themes[themeName];

  try {
    await WebBrowser.openBrowserAsync(url, {
      // Панель браузера красится в цвета приложения — иначе поверх тёмной темы
      // распахивается белая полоса.
      toolbarColor: theme.bg1,
      controlsColor: theme.text,
      enableBarCollapsing: true,
    });
  } catch {
    // Браузера на устройстве может не быть вовсе (урезанные прошивки). Падать
    // из-за ссылки на документ нельзя — экран под ней остаётся рабочим.
  }
}
