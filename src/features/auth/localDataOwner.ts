/**
 * Чей локальный кэш лежит на устройстве (§11).
 *
 * ЗАЧЕМ. Локальная база (§10) — одна на установку: ни `chats`, ни `messages`,
 * ни `outbox` не знают о пользователе. Пока вход один, это незаметно; при
 * смене аккаунта на том же телефоне прошлая история остаётся на диске, и
 * `useChats` показывает её новому человеку — список читается из базы целиком.
 * Проверено вживую: второй аккаунт видел в drawer чат первого, а заголовок
 * чата по B10 — это текст первого вопроса, то есть утекала переписка.
 *
 * РЕШЕНИЕ. Рядом с базой хранится id её владельца. При каждом успешном входе
 * он сверяется с тем, кто вошёл, и при расхождении база стирается ДО первого
 * показа списка. Одна проверка закрывает все пути входа сразу — обычный вход,
 * подтверждение почты, сброс пароля, — и переживает то, чего не переживает
 * выход: приложение могли снять из списка задач, не нажимая «Баромадан».
 *
 * ПОЧЕМУ НЕ user_id В ТАБЛИЦАХ. Второй вариант — добавить колонку и
 * фильтровать. Он сохранил бы офлайн-историю нескольких аккаунтов, но именно
 * этого §11 и не хочет: данные одного человека продолжали бы лежать на
 * телефоне, которым пользуется другой. История — кэш серверной, после входа
 * она подтянется заново; приватность дороже удобства.
 */

/**
 * Нужно ли стереть локальные данные перед тем, как впустить пользователя.
 *
 * Неизвестный прежний владелец (null) тоже считается расхождением. На чистой
 * установке база пуста и стирать нечего — вызов ничего не стоит. А вот после
 * обновления с версии, которая владельца ещё не записывала, на диске может
 * лежать чужое: там лучше один раз потерять офлайн-историю, чем показать её
 * не тому.
 */
export function shouldWipeLocalData(previousOwner: string | null, nextOwner: string): boolean {
  return previousOwner !== nextOwner;
}
