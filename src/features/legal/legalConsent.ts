/**
 * Разбор строки согласия под формой регистрации (§8.2).
 *
 * ПОЧЕМУ НЕ ТРИ КЛЮЧА И НЕ ИНТЕРПОЛЯЦИЯ. Строка «Продолжая, вы соглашаетесь
 * с Условиями использования и Политикой конфиденциальности» содержит две
 * ссылки внутри предложения, и в каждом языке они стоят на своём месте: в
 * английском — в конце, в таджикском — в середине. Склейка из трёх кусков
 * («Бо идома додан, шумо бо» + ссылка + « ва » + ссылка + « розӣ мешавед»)
 * привязала бы порядок слов к коду. Подстановка через {{terms}} ломается о
 * падежи: settings.privacy — это «Политика конфиденциальности» в
 * именительном, а в предложении нужен творительный.
 *
 * Поэтому строка остаётся цельной и переводится целиком, а места ссылок
 * помечены тегами <terms> и <privacy> — теми же, что понимает <Trans> из
 * react-i18next, если однажды понадобится перейти на него.
 *
 * Разбор вынесен из компонента в чистую функцию: единственный способ
 * убедиться, что таджикская, русская и английская строки размечены
 * одинаково, — прогнать все три через тест, а не открывать три экрана.
 */

/** Ссылки, которые разрешено ставить в строке согласия. */
export type ConsentLinkName = 'terms' | 'privacy';

export type ConsentSegment =
  | { kind: 'text'; text: string }
  | { kind: 'link'; name: ConsentLinkName; text: string };

const TAG = /<(terms|privacy)>(.*?)<\/\1>/g;

/**
 * Режет размеченную строку на куски текста и ссылок.
 *
 * Незакрытый или неизвестный тег НЕ ломает экран: непарная разметка
 * останется видимым текстом, и человек всё равно прочитает предложение —
 * регистрация из-за опечатки в словаре не встанет.
 */
export function parseLegalConsent(source: string): ConsentSegment[] {
  const segments: ConsentSegment[] = [];
  let cursor = 0;

  // lastIndex сбрасывается: регулярка с флагом g хранит состояние между
  // вызовами, и второй вызов на той же строке иначе начал бы с середины.
  TAG.lastIndex = 0;

  for (let match = TAG.exec(source); match !== null; match = TAG.exec(source)) {
    if (match.index > cursor) {
      segments.push({ kind: 'text', text: source.slice(cursor, match.index) });
    }
    segments.push({
      kind: 'link',
      name: match[1] as ConsentLinkName,
      text: match[2] ?? '',
    });
    cursor = match.index + match[0].length;
  }

  if (cursor < source.length) {
    segments.push({ kind: 'text', text: source.slice(cursor) });
  }

  return segments;
}
